SUIM_CLASSES = {
    "bw": 0,
    "hd": 1,
    "pf": 2,
    "wr": 3,
    "ro": 4,
    "ri": 5,
    "fv": 6,
    "sr": 7,
}


def find_flat_suim_merged(
    root,
):

    root = Path(root)

    image_candidates = []
    mask_candidates = []

    normalized_image_names = {
        normalize_name(x)
        for x in IMAGE_DIR_NAMES
    }

    # ------------------------------------------------------------
    # Find image directories
    # ------------------------------------------------------------
    for p in root.rglob("*"):

        if not p.is_dir():
            continue

        if (
            normalize_name(p.name)
            not in normalized_image_names
        ):
            continue

        n = count_images(p)

        if n > 0:

            image_candidates.append(
                (
                    n,
                    p,
                )
            )

    # ------------------------------------------------------------
    # Find mask roots
    # ------------------------------------------------------------
    for p in root.rglob("*"):

        if not p.is_dir():
            continue

        if (
            normalize_name(p.name)
            not in {
                "masks",
                "mask",
            }
        ):
            continue

        try:

            children = [
                x
                for x in p.iterdir()
                if x.is_dir()
            ]

        except OSError:

            continue

        class_dirs = []

        for child in children:

            class_name = normalize_name(
                child.name
            )

            if (
                class_name in SUIM_CLASSES
                and count_images(child) > 0
            ):

                class_dirs.append(
                    child
                )

        if class_dirs:

            total = sum(
                count_images(x)
                for x in class_dirs
            )

            mask_candidates.append(
                (
                    total,
                    p,
                )
            )

    if (
        not image_candidates
        or not mask_candidates
    ):

        return None

    image_candidates.sort(
        key=lambda x: x[0],
        reverse=True,
    )

    mask_candidates.sort(
        key=lambda x: x[0],
        reverse=True,
    )

    return {
        "type": "flat",
        "images": image_candidates[0][1],
        "masks": mask_candidates[0][1],
    }


