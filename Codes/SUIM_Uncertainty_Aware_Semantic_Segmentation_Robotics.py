def normalize_name(
    name,
):

    return re.sub(
        r"[^a-z0-9]+",
        "_",
        str(name).lower(),
    ).strip("_")


def compact_name(
    name,
):
    """
    More aggressive normalization.

    Examples:

        f_r_1438_        -> fr1438
        f-r-1438         -> fr1438
        f_r_1438_mask    -> fr1438mask
    """

    normalized = normalize_name(
        name
    )

    return re.sub(
        r"[^a-z0-9]",
        "",
        normalized,
    )


def remove_common_mask_suffixes(
    stem,
):
    """
    Remove harmless naming variations frequently found in
    image/mask datasets.
    """

    value = normalize_name(
        stem
    )

    patterns = [
        r"_mask$",
        r"_masks$",
        r"_label$",
        r"_labels$",
        r"_annotation$",
        r"_annotations$",
        r"_gt$",
        r"_ground_truth$",
        r"_seg$",
        r"_segmentation$",
    ]

    changed = True

    while changed:

        changed = False

        for pattern in patterns:

            new_value = re.sub(
                pattern,
                "",
                value,
            )

            if new_value != value:

                value = new_value
                changed = True

    return value.strip("_")


def extract_numeric_signature(
    stem,
):
    """
    Extract the complete trailing numeric component.

    Example:

        f_r_1438_ -> 1438
        wr_12     -> 12
    """

    value = normalize_name(
        stem
    )

    numbers = re.findall(
        r"\d+",
        value,
    )

    if not numbers:
        return None

    return numbers[-1]


