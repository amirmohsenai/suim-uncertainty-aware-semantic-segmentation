def find_official_splits(
    root,
):

    root = Path(root)

    train_candidates = []
    test_candidates = []

    normalized_image_names = {
        normalize_name(x)
        for x in IMAGE_DIR_NAMES
    }

    normalized_mask_names = {
        normalize_name(x)
        for x in MASK_DIR_NAMES
    }

    all_dirs = [
        p
        for p in root.rglob("*")
        if p.is_dir()
    ]

    for split_dir in all_dirs:

        split_name = normalize_name(
            split_dir.name
        )

        if (
            split_name not in TRAIN_NAMES
            and split_name not in TEST_NAMES
        ):
            continue

        try:

            child_dirs = [
                p
                for p in split_dir.iterdir()
                if p.is_dir()
            ]

        except OSError:

            continue

        image_dir = None
        mask_dir = None

        for child in child_dirs:

            child_name = normalize_name(
                child.name
            )

            if (
                child_name
                in normalized_image_names
                and count_images(child) > 0
            ):

                image_dir = child
                break

        for child in child_dirs:

            child_name = normalize_name(
                child.name
            )

            if (
                child_name
                in normalized_mask_names
                and count_images(child) > 0
            ):

                mask_dir = child
                break

        if (
            image_dir is None
            or mask_dir is None
        ):
            continue

        record = (
            count_images(image_dir),
            split_dir,
            image_dir,
            mask_dir,
        )

        if split_name in TRAIN_NAMES:

            train_candidates.append(
                record
            )

        elif split_name in TEST_NAMES:

            test_candidates.append(
                record
            )

    train_candidates.sort(
        key=lambda x: x[0],
        reverse=True,
    )

    test_candidates.sort(
        key=lambda x: x[0],
        reverse=True,
    )

    if (
        not train_candidates
        or not test_candidates
    ):

        return None

    (
        _,
        train_split,
        train_images,
        train_masks,
    ) = train_candidates[0]

    (
        _,
        test_split,
        test_images,
        test_masks,
    ) = test_candidates[0]

    return {
        "type": "official",
        "train_split": train_split,
        "train_images": train_images,
        "train_masks": train_masks,
        "test_split": test_split,
        "test_images": test_images,
        "test_masks": test_masks,
    }


