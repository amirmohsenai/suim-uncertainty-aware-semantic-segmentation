def extract_zip_safely(
    zip_path,
    destination,
):

    zip_path = Path(zip_path)
    destination = Path(destination)

    destination.mkdir(
        parents=True,
        exist_ok=True,
    )

    destination_resolved = (
        destination.resolve()
    )

    with zipfile.ZipFile(
        zip_path,
        "r",
    ) as zf:

        for member in zf.infolist():

            target = (
                destination
                / member.filename
            ).resolve()

            try:

                target.relative_to(
                    destination_resolved
                )

            except ValueError:

                raise RuntimeError(
                    "Unsafe ZIP path detected:\n"
                    f"{member.filename}"
                )

        zf.extractall(
            destination
        )


