def list_image_files(
    directory,
):

    directory = Path(directory)

    if not directory.is_dir():
        return []

    return sorted(
        [
            p
            for p in directory.iterdir()
            if is_image_file(p)
        ],
        key=lambda p: p.name.lower(),
    )


def count_images(
    directory,
):

    return len(
        list_image_files(
            directory
        )
    )


