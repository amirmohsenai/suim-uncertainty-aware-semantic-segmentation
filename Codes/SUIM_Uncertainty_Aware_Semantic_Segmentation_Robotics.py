    for image_path in remaining_images:

        image_key = compact_name(
            remove_common_mask_suffixes(
                image_path.stem
            )
        )

        if not image_key:
            continue

        scored = []

        for mask_path, mask_key in (
            normalized_remaining_masks.items()
        ):

            if str(mask_path) in used_masks:
                continue

            ratio = difflib.SequenceMatcher(
                None,
                image_key,
                mask_key,
            ).ratio()

            scored.append(
                (
                    ratio,
                    mask_path,
                )
            )

        scored.sort(
            key=lambda x: x[0],
            reverse=True,
        )

